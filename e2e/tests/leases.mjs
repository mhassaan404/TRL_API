// Buildings, floors, units, tenants and the lease lifecycle (create, edit, renew, cancel renewal, end, cancel)
import { DB, TODAY, addDays, apiTenancy, area, errorText, monthStart, num, ok, one, section, sql } from '../lib.mjs'

export default async ({ a }) => {
  area('leases')
  const db = DB.a

  section('buildings, floors and units')
  const t = await apiTenancy(a, db, { units: 2 })
  ok(t.buildingId > 0 && t.floorId > 0 && t.unitIds.length === 2 && t.tenantId > 0, 'building, floor, 2 units and a tenant created through the API', t)
  const bName = one(db, `SELECT BuildingName FROM Buildings WHERE BuildingId = ${t.buildingId}`)
  let r = await a.post('/Properties/SaveBuilding', { buildingName: bName, cityId: 1, typeId: 1 })
  ok(r.status === 400 && /already exists/.test(errorText(r)), 'duplicate building name refused', r.json)
  r = await a.post('/Properties/SaveBuilding', { buildingName: '  ', cityId: 1, typeId: 1 })
  ok(r.status === 400 && /required/.test(errorText(r)), 'empty building name refused', r.json)
  r = await a.post('/Properties/SaveFloor', { buildingId: t.buildingId, floorNumber: '1' })
  ok(r.status === 400 && /already has floor/.test(errorText(r)), 'duplicate floor refused', r.json)
  r = await a.post('/Properties/SaveUnit', { buildingId: t.buildingId, floorId: t.floorId, unitNumber: 'U1', statusId: 1, baseRent: 1 })
  ok(r.status === 400 && /already has unit/.test(errorText(r)), 'duplicate unit number in the same building refused', r.json)
  r = await a.post('/Properties/SaveUnit', { buildingId: t.buildingId, floorId: t.floorId, unitNumber: 'NEG', statusId: 1, baseRent: -5 })
  ok(r.status === 400 && /negative/.test(errorText(r)), 'negative base rent refused', r.json)
  const other = await apiTenancy(a, db, {})
  r = await a.post('/Properties/SaveUnit', { buildingId: t.buildingId, floorId: other.floorId, unitNumber: 'MIX', statusId: 1, baseRent: 1 })
  ok(r.status === 400 && /doesn't belong to the selected building/.test(errorText(r)) && num(db, `SELECT COUNT(*) FROM Units WHERE UnitNumber = N'MIX'`) === 0,
     "unit on another building's floor refused", r.json)
  r = await a.post('/Properties/SaveUnit', { buildingId: t.buildingId, floorId: t.floorId, unitNumber: 'DEC', statusId: 1, baseRent: 12345.67 })
  ok(r.status === 200 && one(db, `SELECT CONVERT(varchar(20), BaseRent) FROM Units WHERE UnitId = ${r.json?.id}`) === '12345.67', 'base rent with paisa stored exactly', r.json)
  r = await a.put('/Properties/UpdateUnit', { unitId: r.json?.id, buildingId: t.buildingId, floorId: other.floorId, unitNumber: 'DEC', statusId: 1, baseRent: 1 })
  ok(r.status === 400 && /doesn't belong/.test(errorText(r)), "unit can't be moved to another building's floor", r.json)
  const floors = (await a.get(`/Properties/GetFloorsByBuilding/${t.buildingId}`)).json
  ok(Array.isArray(floors) && floors.length === 1, 'GetFloorsByBuilding lists the floor', floors)

  section('tenants')
  r = await a.post('/Tenant/Create', { name: 'E2E Bad Phone', tenantType: 'Individual', contact: '12345', cnicNtn: '42101-1234567-1', cityId: 1 })
  ok(r.status === 400 && /phone/i.test(errorText(r)), 'invalid phone refused', r.json)
  r = await a.post('/Tenant/Create', { name: 'E2E Bad CNIC', tenantType: 'Individual', contact: '0300-1234567', cnicNtn: '123', cityId: 1 })
  ok(r.status === 400 && /CNIC/i.test(errorText(r)), 'invalid CNIC refused', r.json)
  r = await a.post('/Tenant/Create', { name: 'E2E Bad Type', tenantType: 'Robot', contact: '0300-1234567', cityId: 1 })
  ok(r.status === 400 && /Company or Individual/.test(errorText(r)), 'invalid tenant type refused', r.json)
  const tenants = (await a.get('/Tenant/GetTenants')).json
  ok(Array.isArray(tenants) && tenants.some((x) => x.tenantId === t.tenantId), 'tenant listed')
  ok(one(db, `SELECT CONCAT(ISNULL(UnitId, 0), '|', ISNULL(MonthlyRent, 0)) FROM Tenants WHERE TenantId = ${t.tenantId}`) === '0|0.00',
     'unit and rent sent with a new tenant are ignored (only a lease sets them)')

  section('create a lease')
  const vacant = async () => ((await a.get('/Rent/GetVacantUnits')).json || []).map((u) => u.unitId)
  ok((await vacant()).includes(t.unitIds[0]), 'unit is vacant before the lease')
  const start = monthStart(TODAY, -1)
  r = await a.post('/Lease/Create', { tenantId: t.tenantId, unitId: t.unitIds[0], rentAmount: 0, startDate: start, tenureMonths: 12 })
  ok(r.status === 400 && /greater than zero/.test(errorText(r)), 'zero rent refused', r.json)
  r = await a.post('/Lease/Create', { tenantId: t.tenantId, unitId: t.unitIds[0], rentAmount: 40000, startDate: start, tenureMonths: 0 })
  ok(r.status === 400 && /Tenure/.test(errorText(r)), 'zero tenure refused', r.json)
  r = await a.post('/Lease/Create', { tenantId: t.tenantId, unitId: t.unitIds[0], rentAmount: 40000, startDate: start, tenureMonths: 12 })
  ok(r.status === 200, 'lease created', r.json)
  const leaseId = num(db, `SELECT MAX(LeaseId) FROM TenantLeases WHERE TenantId = ${t.tenantId}`)
  ok(one(db, `SELECT CONCAT(IsActive, '|', UnitId, '|', RentAmount) FROM TenantLeases WHERE LeaseId = ${leaseId}`) === `1|${t.unitIds[0]}|40000.00`, 'lease row active with the rent and unit')
  ok(num(db, `SELECT UnitId FROM Tenants WHERE TenantId = ${t.tenantId}`) === t.unitIds[0], 'tenant now points at the unit')
  ok(!(await vacant()).includes(t.unitIds[0]), 'unit no longer vacant')
  r = await a.post('/Lease/Create', { tenantId: t.tenantId, unitId: t.unitIds[0], rentAmount: 40000, startDate: TODAY, tenureMonths: 12 })
  ok(r.status === 400, 'second active lease on the same unit refused', r.json)
  const list = (await a.get('/Lease/GetAll')).json
  ok(list.some((l) => l.leaseId === leaseId), 'lease listed in Lease Management')

  section('edit, renew, cancel renewal')
  r = await a.post('/Lease/Update', { leaseId, startDate: start, rentAmount: 40000, tenureMonths: 18 })
  ok(r.status === 200 && num(db, `SELECT TenureMonths FROM TenantLeases WHERE LeaseId = ${leaseId}`) === 18, 'tenure edited', r.json)
  r = await a.post('/Lease/Update', { leaseId, startDate: start, rentAmount: 40000, tenureMonths: 18 })
  ok(r.status === 400 && /Nothing was changed/.test(errorText(r)), 'edit without changes refused', r.json)
  r = await a.post('/Lease/Renew', { leaseId, newRentAmount: 0, tenureMonths: 12 })
  ok(r.status === 400 && /greater than zero/.test(errorText(r)), 'renewal with zero rent refused', r.json)
  r = await a.post('/Lease/Renew', { leaseId, newRentAmount: 45000, tenureMonths: 12 })
  ok(r.status === 200, 'lease renewed', r.json)
  const renewal = num(db, `SELECT MAX(LeaseId) FROM TenantLeases WHERE TenantId = ${t.tenantId}`)
  const [prevState] = sql(db, `SELECT IsActive, TerminationReason, CONVERT(varchar(10), BilledThrough, 23), CONVERT(varchar(10), EndDate, 23) FROM TenantLeases WHERE LeaseId = ${leaseId}`)
  const [newState] = sql(db, `SELECT IsActive, RentAmount, CONVERT(varchar(10), StartDate, 23) FROM TenantLeases WHERE LeaseId = ${renewal}`)
  ok(renewal > leaseId && prevState[0] === '0' && prevState[1] === 'Renewed' && newState[0] === '1' && Number(newState[1]) === 45000,
     'old term marked Renewed, new term active at the new rent', { prevState, newState })
  ok(prevState[2] === addDays(newState[2], -1), 'old term billed through the day before the new term starts', { prevState, newState })
  r = await a.post('/Lease/CancelRenewal', { leaseId: renewal })
  ok(r.status === 200 && /Renewal cancelled/.test(r.json?.message), 'upcoming renewal cancelled', r.json)
  ok(one(db, `SELECT CONCAT(IsActive, '|', ISNULL(TerminationReason, '')) FROM TenantLeases WHERE LeaseId = ${renewal}`) === '0|Renewal cancelled' &&
     one(db, `SELECT CONCAT(IsActive, '|', ISNULL(CONVERT(varchar(10), BilledThrough, 23), 'NULL')) FROM TenantLeases WHERE LeaseId = ${leaseId}`) === '1|NULL',
     'renewal inactive, original lease active again')
  r = await a.post('/Lease/CancelRenewal', { leaseId })
  ok(r.status === 400, 'a lease that is not a renewal cannot be "cancelled as renewal"', r.json)

  section('end a lease')
  r = await a.post('/Lease/Terminate', { leaseId, reason: '  ', moveOutDate: TODAY })
  ok(r.status === 400 && /reason/.test(errorText(r)), 'end without reason refused', r.json)
  r = await a.post('/Lease/Terminate', { leaseId, reason: 'x', moveOutDate: addDays(TODAY, 1) })
  ok(r.status === 400 && /future/.test(errorText(r)), 'future move-out refused', r.json)
  r = await a.post('/Lease/Terminate', { leaseId, reason: 'x', moveOutDate: addDays(start, -1) })
  ok(r.status === 400 && /before the lease start/.test(errorText(r)), 'move-out before the start refused', r.json)
  r = await a.post('/Lease/Terminate', { leaseId, reason: 'E2E moved out', moveOutDate: TODAY })
  ok(r.status === 200 && /billed through/.test(r.json?.message), 'lease ended', r.json)
  ok(one(db, `SELECT CONCAT(IsActive, '|', CONVERT(varchar(10), BilledThrough, 23), '|', TerminationReason) FROM TenantLeases WHERE LeaseId = ${leaseId}`) === `0|${TODAY}|E2E moved out`,
     'lease inactive, billed through the move-out day, reason stored')
  ok((await vacant()).includes(t.unitIds[0]), 'unit vacant again')
  const occupied = async (unitId) => ((await a.get('/Properties/GetProperties')).json || []).find((u) => u.unitId === unitId)?.isOccupied
  ok(num(db, `SELECT IsActive FROM Tenants WHERE TenantId = ${t.tenantId}`) === 0 && (await occupied(t.unitIds[0])) === false, 'tenant moved out, unit not occupied')
  r = await a.put('/Tenant/Update', { tenantId: t.tenantId, name: t.name, tenantType: 'Individual', contact: '0300-1234567', isActive: true })
  ok(r.status === 200 && one(db, `SELECT CONCAT(IsActive, '|', ISNULL(UnitId, 0)) FROM Tenants WHERE TenantId = ${t.tenantId}`) === '1|0',
     'reactivating a tenant without a lease clears the old unit', r.json)
  ok((await occupied(t.unitIds[0])) === false, 'so the old unit does not show as occupied')

  section('cancel a lease made by mistake')
  r = await a.post('/Lease/Create', { tenantId: t.tenantId, unitId: t.unitIds[1], rentAmount: 30000, startDate: monthStart(TODAY), tenureMonths: 6 })
  const mistake = num(db, `SELECT MAX(LeaseId) FROM TenantLeases WHERE TenantId = ${t.tenantId}`)
  ok(r.status === 200, 'second lease created on the other unit', r.json)
  const month = Number(TODAY.slice(5, 7))
  const year = Number(TODAY.slice(0, 4))
  r = await a.post('/Rent/GenerateInvoices', { tenantIds: [t.tenantId], month, year })
  const inv = num(db, `SELECT MAX(Id) FROM RentInvoices WHERE LeaseId = ${mistake}`)
  ok(r.status === 200 && inv > 0, 'its rent invoice generated', r.json)
  r = await a.post('/Rent/SubmitPayments', [{ tenantId: t.tenantId, rentInvoiceId: inv, paymentAmount: 1000, paymentDate: TODAY, paymentMethod: 'Cash', discountAmount: 0, discountPercent: 0, isLateFeeWaived: false }])
  const pay = num(db, `SELECT MAX(Id) FROM Payments WHERE RentInvoiceId = ${inv}`)
  r = await a.post('/Lease/Cancel', { leaseId: mistake })
  ok(r.status === 400 && /Reverse them first/.test(errorText(r)), 'cancel refused while the invoice has a payment', r.json)
  await a.post('/Rent/ReversePayment', { paymentId: pay, reason: 'e2e: wrong lease' })
  r = await a.post('/Lease/Cancel', { leaseId: mistake })
  ok(r.status === 200 && one(db, `SELECT CONCAT(IsActive, '|', TerminationReason) FROM TenantLeases WHERE LeaseId = ${mistake}`) === '0|Lease cancelled',
     'cancel allowed once every payment is reversed', r.json)
  ok(num(db, `SELECT StatusId FROM RentInvoices WHERE Id = ${inv}`) === 6 && num(db, `SELECT COUNT(*) FROM Payments WHERE RentInvoiceId = ${inv}`) === 2,
     'its invoice is cancelled; the payment and its reversal are kept')

  r = await a.post('/Lease/Create', { tenantId: t.tenantId, unitId: t.unitIds[1], rentAmount: 30000, startDate: addDays(TODAY, 30), tenureMonths: 6 })
  const upcoming = num(db, `SELECT MAX(LeaseId) FROM TenantLeases WHERE TenantId = ${t.tenantId}`)
  ok(r.status === 200, 'upcoming lease created', r.json)
  r = await a.post('/Lease/Cancel', { leaseId: upcoming })
  ok(r.status === 200 && one(db, `SELECT CONCAT(IsActive, '|', TerminationReason) FROM TenantLeases WHERE LeaseId = ${upcoming}`) === '0|Lease cancelled',
     'lease without payments cancelled as a mistake', r.json)
  ok(num(db, `SELECT COUNT(*) FROM RentInvoices WHERE LeaseId = ${upcoming} AND StatusId <> 6`) === 0, 'no open invoices left on the cancelled lease')

  section('deleting property that is in use (separate data)')
  {
    const d = await apiTenancy(a, db, { start: monthStart(TODAY), units: 1 })
    const active = (table, key, id) => num(db, `SELECT IsActive FROM ${table} WHERE ${key} = ${id}`)
    r = await a.del(`/Properties/DeleteUnit/${d.unitId}`)
    ok(r.status === 400 && /active or upcoming lease/.test(errorText(r)) && active('Units', 'UnitId', d.unitId) === 1, 'unit with an active lease cannot be deleted', r.json)
    r = await a.del(`/Properties/DeleteFloor/${d.floorId}`)
    ok(r.status === 400 && /still has units/.test(errorText(r)) && active('Floors', 'FloorId', d.floorId) === 1, 'floor with units cannot be deleted', r.json)
    r = await a.del(`/Properties/DeleteBuilding/${d.buildingId}`)
    ok(r.status === 400 && /floors or units/.test(errorText(r)) && active('Buildings', 'BuildingId', d.buildingId) === 1, 'building with floors cannot be deleted', r.json)
    ok(num(db, `SELECT IsActive FROM TenantLeases WHERE LeaseId = ${d.leaseId}`) === 1, 'the lease is not changed')

    // Once the lease has ended, the unit, then the floor, then the building can go
    await a.post('/Lease/Terminate', { leaseId: d.leaseId, reason: 'E2E delete test', moveOutDate: TODAY })
    r = await a.del(`/Properties/DeleteBuilding/${d.buildingId}`)
    ok(r.status === 400, 'building still refused while its unit exists')
    r = await a.del(`/Properties/DeleteUnit/${d.unitId}`)
    ok(r.status === 200 && active('Units', 'UnitId', d.unitId) === 0, 'unit deleted after the lease ended', r.json)
    r = await a.del(`/Properties/DeleteFloor/${d.floorId}`)
    ok(r.status === 200 && active('Floors', 'FloorId', d.floorId) === 0, 'empty floor deleted', r.json)
    r = await a.del(`/Properties/DeleteBuilding/${d.buildingId}`)
    ok(r.status === 200 && active('Buildings', 'BuildingId', d.buildingId) === 0, 'empty building deleted', r.json)
    r = await a.del(`/Properties/DeleteBuilding/${d.buildingId}`)
    ok(r.status === 400 && /not found or already deleted/.test(errorText(r)), 'deleting twice is refused', r.json)
    ok(num(db, `SELECT COUNT(*) FROM TenantLeases WHERE LeaseId = ${d.leaseId}`) === 1, 'lease history kept (soft delete only)')
  }

  section('lease create checks (deleted tenant / unit, bad dates)')
  {
    const x = await apiTenancy(a, db, { units: 2 })
    const lease = (over) => a.post('/Lease/Create', { tenantId: x.tenantId, unitId: x.unitIds[0], rentAmount: 30000, startDate: TODAY, tenureMonths: 12, ...over })
    const leases = () => num(db, `SELECT COUNT(*) FROM TenantLeases WHERE TenantId = ${x.tenantId}`)
    r = await lease({ startDate: '0001-01-01' })
    ok(r.status === 400 && /start date/.test(errorText(r)), 'impossible start date refused (was a server error)', r.json)
    r = await a.del(`/Properties/DeleteUnit/${x.unitIds[1]}`)
    r = await lease({ unitId: x.unitIds[1] })
    ok(r.status === 400 && /unit doesn't exist or has been deleted/.test(errorText(r)), 'lease on a deleted unit refused', r.json)
    r = await lease({ unitId: 99999999 })
    ok(r.status === 400 && /unit doesn't exist/.test(errorText(r)), 'lease on a unit that does not exist refused', r.json)
    r = await a.del(`/Tenant/Delete?tenantId=${x.tenantId}`)
    ok(r.status === 200, 'tenant without a lease deleted', r.json)
    r = await lease({})
    ok(r.status === 400 && /tenant doesn't exist or has been deleted/.test(errorText(r)), 'lease for a deleted tenant refused (it would never be billed)', r.json)
    ok(leases() === 0, 'no lease rows written by the refused requests')
  }
}
